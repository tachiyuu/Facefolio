# Regenerates app/src/main/res/raw/be_vietnam_pro.js from the TTFs in res/font.
# Usage: python tools/build-font-script.py   (needs: pip install fonttools brotli)
import base64, io, os
from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = os.path.join(os.path.dirname(__file__), '..', 'app', 'src', 'main', 'res')
# Latin + Vietnamese only: everything else (and Facebook's private-use icon glyphs) falls through
# to Facebook's own fonts.
RANGE = ('U+0020-007E, U+00A0-00FF, U+0102-0103, U+0110-0111, U+0128-0129, U+0131, U+0152-0153, U+0168-0169, '
         'U+01A0-01A1, U+01AF-01B0, U+02C6, U+02DA, U+02DC, U+0300-0301, U+0303, U+0309, U+0323, U+1EA0-1EF9, '
         'U+2013-2014, U+2018-201A, U+201C-201E, U+2022, U+2026, U+20AB, U+20AC, U+2122')

def unicodes():
    out = []
    for part in RANGE.replace('U+', '').split(','):
        lo, _, hi = part.strip().partition('-')
        out.extend(range(int(lo, 16), int(hi or lo, 16) + 1))
    return out

def woff2(name):
    font = TTFont(os.path.join(ROOT, 'font', name))
    options = subset.Options(flavor='woff2', layout_features=['kern', 'liga', 'mark', 'mkmk', 'ccmp', 'locl'])
    sub = subset.Subsetter(options)
    sub.populate(unicodes=unicodes())
    sub.subset(font)
    font.flavor = 'woff2'
    buf = io.BytesIO()
    font.save(buf)
    return base64.b64encode(buf.getvalue()).decode()

fonts = ''.join(f"        [{weight}, '{woff2(name)}'],\n"
                for weight, name in ((400, 'be_vietnam_pro_regular.ttf'), (600, 'be_vietnam_pro_semibold.ttf')))

js = f"""// Generated by tools/build-font-script.py, do not edit.
// Be Vietnam Pro for Facebook's pages, offline and CSP-safe (data: URLs).
// Facebook sets its text in 'Roboto-V2' (mobile) with Roboto / system-ui fallbacks. Adding faces to those
// families, limited to Latin and Vietnamese by unicode-range, swaps the text font without touching any
// element style, so Facebook's icon fonts (private-use glyphs) keep rendering. Among faces of one family
// the last declared wins, and this runs after Facebook's stylesheet. Each font file appears once.
(function() {{
    'use strict';
    const RANGE = '{RANGE}';
    const FONTS = [
{fonts}    ];
    // 500 and 700 map to the semibold file: Facebook uses both for emphasis
    const WEIGHTS = {{ 400: '400', 600: '500 700' }};
    // Roboto-V2: Facebook mobile. Roboto and system-ui: desktop layout and fallbacks.
    const FAMILIES = ['Roboto-V2', 'Roboto', 'system-ui'];
    // Decoded to bytes once; FontFace takes the buffer, so no font data is repeated in CSS text
    const bytes = FONTS.map(([weight, data]) => [weight, Uint8Array.from(atob(data), c => c.charCodeAt(0))]);
    for (const family of FAMILIES) {{
        for (const [weight, buffer] of bytes) {{
            const face = new FontFace(family, buffer.slice(), {{ weight: WEIGHTS[weight], unicodeRange: RANGE, display: 'swap' }});
            face.load().then(() => document.fonts.add(face), () => {{}});
        }}
    }}
}})();
"""
with open(os.path.join(ROOT, 'raw', 'be_vietnam_pro.js'), 'w', encoding='utf-8', newline='\n') as f:
    f.write(js)
print(f'be_vietnam_pro.js: {len(js) // 1024} KB')
